import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const req = createRequire("/opt/npm-tools/node_modules/");
const esbuild = req("esbuild");
const { chromium } = req("playwright");
const out = await esbuild.build({ entryPoints: ["tools/gallery/entry.ts"], bundle: true, write: false, format: "iife", loader: { ".jpg": "dataurl", ".png": "dataurl" } });
const js = out.outputFiles[0].text;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1240, height: 900 } });
p.on("pageerror", (e) => console.log("ERR", String(e)));
await p.setContent(`<body><script>${js.replace(/<\/script/g, "<\\/script")}</script></body>`);
await p.waitForFunction(() => window.done, null, { timeout: 15000 });
await p.waitForTimeout(300);
const el = p.locator("canvas");
const box = await el.boundingBox();
const h = Math.ceil(box.height);
const part = Number(process.argv[2] ?? 0);
await p.screenshot({ path: `dist/shots/gallery-${part}.png`, fullPage: true, clip: { x: 0, y: part * 800, width: 1240, height: Math.min(800, h - part * 800) } });
console.log("altezza", h);
await b.close();
